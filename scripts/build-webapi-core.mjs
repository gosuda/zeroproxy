#!/usr/bin/env node
import { rm, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(repoRoot, 'web', 'runtime', 'webapi', 'core-realm-entry.mjs');
const generated = path.join(repoRoot, 'web', 'runtime', 'webapi', 'core-source.generated.mjs');
const outDir = path.join(repoRoot, 'dist', '.webapi-core-source');
const bundleName = 'webapi-core-realm.js';

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });
await build({
  configFile: false,
  root: repoRoot,
  appType: 'custom',
  publicDir: false,
  logLevel: 'warn',
  build: {
    target: 'es2022',
    outDir,
    emptyOutDir: true,
    minify: false,
    modulePreload: false,
    cssCodeSplit: false,
    rollupOptions: {
      input: entry,
      treeshake: false,
      output: {
        entryFileNames: bundleName,
        format: 'iife',
        name: 'ZeroProxyWebAPICoreRealmBundle',
        inlineDynamicImports: true,
      },
    },
  },
});

const source = await readFile(path.join(outDir, bundleName), 'utf8');
await writeFile(generated, renderGeneratedSource(source));
process.stdout.write(
  `Built ${path.relative(repoRoot, generated)} from ${path.relative(repoRoot, entry)}\n`,
);

function renderGeneratedSource(source) {
  const lines = source.split('\n');
  const encoded = lines
    .map((line) => '  ' + JSON.stringify(line).replaceAll('${', '\\u0024{'))
    .join(',\n');
  return `// Generated by scripts/build-webapi-core.mjs. Do not edit by hand.\nexport const WEBAPI_CORE_SOURCE = [\n${encoded}\n].join('\\n');\n`;
}
