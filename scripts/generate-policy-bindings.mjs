import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const input = new URL("../protocol/route-spec.json", import.meta.url);
const output = new URL("../web/generated/route-spec.mjs", import.meta.url);
const classicOutput = new URL("../web/generated/route-spec-classic.js", import.meta.url);

function fail(message) {
  throw new Error(`route-spec: ${message}`);
}

function exactRoutes(value) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) fail("exact_routes must be an object");
  const entries = Object.entries(value);
  if (entries.length === 0) fail("exact_routes must not be empty");
  for (const [path, kind] of entries) {
    if (typeof path !== "string" || !path.startsWith("/") || path.includes("?") || path.includes("#")) fail("invalid exact route path");
    if (typeof kind !== "string" || !/^[a-z-]+$/u.test(kind)) fail("invalid exact route kind");
  }
  return entries.sort(([left], [right]) => left.localeCompare(right));
}

function routePatterns(value) {
  if (!Array.isArray(value) || value.length === 0) fail("route_patterns must be a non-empty array");
  return value.map((entry) => {
    if (!Array.isArray(entry) || entry.length !== 2) fail("invalid route pattern entry");
    const [kind, pattern] = entry;
    if (typeof kind !== "string" || !/^[a-z-]+$/u.test(kind)) fail("invalid route pattern kind");
    if (typeof pattern !== "string" || !pattern.startsWith("^/") || !pattern.endsWith("$") && !pattern.endsWith("/")) fail("invalid route pattern");
    try { new RegExp(pattern, "u"); } catch { fail("invalid route regular expression"); }
    return [kind, pattern];
  });
}

function sealedRouteKinds(value) {
  if (!Array.isArray(value) || value.length === 0 || new Set(value).size !== value.length) fail("sealed_route_kinds must be a non-empty unique array");
  for (const kind of value) if (typeof kind !== "string" || !/^[a-z-]+$/u.test(kind)) fail("invalid sealed route kind");
  return value;
}

function targetRouteKinds(value) {
  if (!Array.isArray(value) || value.length === 0 || new Set(value).size !== value.length) fail("target_route_kinds must be a non-empty unique array");
  for (const kind of value) if (typeof kind !== "string" || !/^[a-z-]+$/u.test(kind)) fail("invalid target route kind");
  return value;
}

const spec = JSON.parse(await readFile(input, "utf8"));
if (spec?.schema_version !== 1 || spec.policy_version !== 2 || Object.keys(spec).some((key) => !["schema_version", "policy_version", "sealed_route_kinds", "target_route_kinds", "exact_routes", "route_patterns"].includes(key))) fail("invalid top-level schema");
const exact = exactRoutes(spec.exact_routes);
const sourcePatterns = routePatterns(spec.route_patterns);
const sealedKinds = sealedRouteKinds(spec.sealed_route_kinds);
const targetKinds = targetRouteKinds(spec.target_route_kinds);
if (sourcePatterns.some(([kind]) => kind === "target-route" || kind === "sealed-route")) fail("derived route kinds must not be hand-authored");
const targetPattern = `^/_zp/p/(${targetKinds.join("|")})/[A-Za-z0-9_-]{32}$`;
const sealedPattern = `^/_zp/(${sealedKinds.join("|")})/[a-f0-9]{48}/[A-Za-z0-9_-]{1,16384}$`;
const patterns = [];
for (const pattern of sourcePatterns) {
  patterns.push(pattern);
  if (pattern[0] === "internal-immutable-asset") patterns.push(["target-route", targetPattern]);
  if (pattern[0] === "api-plan") patterns.push(["sealed-route", sealedPattern]);
}
if (!patterns.some(([kind]) => kind === "target-route") || !patterns.some(([kind]) => kind === "sealed-route")) fail("route pattern derivation failed");
const content = `// Generated by scripts/generate-policy-bindings.mjs from protocol/route-spec.json.\nexport const ROUTE_SPEC_POLICY_VERSION = ${spec.policy_version};\n\nexport const EXACT_ROUTES = new Map(${JSON.stringify(exact)});\n\nexport const ROUTE_TABLE = Object.freeze([\n${patterns.map(([kind, pattern]) => `  Object.freeze({ kind: ${JSON.stringify(kind)}, pattern: new RegExp(${JSON.stringify(pattern)}, "u") }),`).join("\n")}\n]);\n\nconst TARGET_ROUTE_PATTERN = new RegExp(${JSON.stringify(targetPattern)}, "u");\nexport function targetRouteKind(pathname) {\n  if (typeof pathname !== "string") return null;\n  return TARGET_ROUTE_PATTERN.exec(pathname)?.[1] ?? null;\n}\n`;
const classicContent = `// Generated by scripts/generate-policy-bindings.mjs from protocol/route-spec.json.\nconst __zpBuildSealedRoute=Object.freeze((includes,test,kind,operationID,token)=>{if(!includes(${JSON.stringify(sealedKinds)},kind)||!test(/^[a-f0-9]{48}$/u,operationID)||!test(/^[A-Za-z0-9_-]{1,16384}$/u,token))return null;return \`/_zp/\${kind}/\${operationID}/\${token}\`;});\nconst __zpBuildHistoryRoute=Object.freeze((test,entryID,token)=>{if(!test(/^[A-Za-z0-9_-]{32}$/u,entryID)||!test(/^[A-Za-z0-9_-]{1,16384}$/u,token))return null;return \`/_zp/history/\${entryID}/\${token}\`;});\n`;
if (process.argv.includes("--check")) {
  const [existing, existingClassic] = await Promise.all([
    readFile(output, "utf8").catch(() => null),
    readFile(classicOutput, "utf8").catch(() => null),
  ]);
  if (existing !== content || existingClassic !== classicContent) fail(`generated binding is stale; run ${fileURLToPath(new URL("./generate-policy-bindings.mjs", import.meta.url))}`);
} else {
  await Promise.all([writeFile(output, content), writeFile(classicOutput, classicContent)]);
}
