import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "protocol/owned-globals.json");
const rustPath = resolve(root, "crates/js-compiler/src/generated_owned_globals.rs");
const jsPath = resolve(root, "web/generated/owned-globals.mjs");
const argumentsList = process.argv.slice(2);
const check = argumentsList.length === 1 && argumentsList[0] === "--check";
if (argumentsList.length !== 0 && !check) throw new Error("usage: generate-owned-globals.mjs [--check]");

const source = JSON.parse(await readFile(sourcePath, "utf8"));
const categories = new Set([
  "document-state",
  "dynamic-code",
  "global-identity-navigation",
  "messaging-lifecycle",
  "network",
  "network-disabled",
  "scheduling",
]);
if (source.schema_version !== 1 || source.registry_version !== 1 || !Array.isArray(source.entries)) {
  throw new Error("invalid owned-global registry header");
}

const seen = new Set();
let previousName = "";
for (const entry of source.entries) {
  if (!entry || typeof entry !== "object" || Array.isArray(entry)) throw new Error("invalid owned-global entry");
  if (Object.keys(entry).sort().join(",") !== "category,name") throw new Error("invalid owned-global entry fields");
  if (typeof entry.name !== "string" || !/^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(entry.name)) {
    throw new Error(`invalid owned-global name ${JSON.stringify(entry.name)}`);
  }
  if (!categories.has(entry.category)) throw new Error(`invalid owned-global category ${JSON.stringify(entry.category)}`);
  if (seen.has(entry.name)) throw new Error(`duplicate owned-global name ${entry.name}`);
  if (previousName !== "" && previousName >= entry.name) throw new Error("owned-global entries are not sorted by name");
  seen.add(entry.name);
  previousName = entry.name;
}
if (source.entries.length === 0) throw new Error("owned-global registry must not be empty");

const rustNames = source.entries.map(entry => `    ${JSON.stringify(entry.name)},`).join("\n");
const rust = `// Generated by scripts/generate-owned-globals.mjs. DO NOT EDIT.\n\npub const OWNED_GLOBAL_REGISTRY_VERSION: u32 = ${source.registry_version};\npub const OWNED_GLOBALS: &[&str] = &[\n${rustNames}\n];\n\npub fn is_owned_global(name: &str) -> bool {\n    OWNED_GLOBALS.binary_search(&name).is_ok()\n}\n`;
const entriesJSON = JSON.stringify(source.entries);
const js = `// Generated by scripts/generate-owned-globals.mjs. DO NOT EDIT.\nexport const OWNED_GLOBAL_REGISTRY_VERSION = ${source.registry_version};\nexport const OWNED_GLOBAL_REGISTRY = Object.freeze(${entriesJSON}.map(Object.freeze));\nexport const OWNED_GLOBALS = Object.freeze(OWNED_GLOBAL_REGISTRY.map(entry => entry.name));\nexport const DISABLED_NETWORK_GLOBALS = Object.freeze(OWNED_GLOBAL_REGISTRY.filter(entry => entry.category === "network-disabled").map(entry => entry.name));\nexport function isOwnedGlobal(name) {\n  if (typeof name !== "string") return false;\n  let low = 0;\n  let high = OWNED_GLOBALS.length;\n  while (low < high) {\n    const middle = low + ((high - low) >> 1);\n    const candidate = OWNED_GLOBALS[middle];\n    if (candidate < name) low = middle + 1;\n    else high = middle;\n  }\n  return OWNED_GLOBALS[low] === name;\n}\n`;

async function sync(path, content) {
  let current = null;
  try {
    current = await readFile(path, "utf8");
  } catch {}
  if (current === content) return;
  if (check) throw new Error(`generated owned-global registry is stale: ${path}`);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}
await sync(rustPath, rust);
await sync(jsPath, js);
