import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const sourcePath = path.join(root, "protocol/stealth-profile.json");
const supportPath = path.join(root, "protocol/support-matrix.json");
const outputPath = path.join(root, "web/generated/stealth-profile.mjs");
const mode = process.argv[2] ?? "";
if (!["", "--check"].includes(mode)) throw new Error("usage: generate-stealth-profile.mjs [--check]");

const requiredSurfaces = Object.freeze([
  "global-equality",
  "window-location-reflection",
  "canonical-wrapper-identity",
  "function-reflection",
  "target-dom",
  "parser-ordering",
  "errors-and-source",
  "performance-observability",
  "policy-violations",
  "target-service-worker",
  "internal-url-concealment",
  "root-injection-concealment",
]);
const [source, support] = await Promise.all([
  readFile(sourcePath, "utf8").then(JSON.parse),
  readFile(supportPath, "utf8").then(JSON.parse),
]);
if (source.schema_version !== 1
  || source.profile_id !== "bounded-compatibility-v2"
  || source.universal_undetectability_claim !== false
  || !Array.isArray(source.surfaces)
  || source.surfaces.length !== requiredSurfaces.length) {
  throw new Error("invalid stealth profile header");
}
const scope = support.browsers.map(({ family, exact_build, platform }) => ({ family, exact_build, platform }));
if (JSON.stringify(source.browser_scope) !== JSON.stringify(scope)) throw new Error("stealth browser scope differs from support matrix");
const probeIDs = new Set();
let probeCount = 0;
for (let index = 0; index < requiredSurfaces.length; index += 1) {
  const surface = source.surfaces[index];
  if (surface.id !== requiredSurfaces[index] || !Array.isArray(surface.probes) || surface.probes.length < 3) {
    throw new Error(`invalid stealth surface ${requiredSurfaces[index]}`);
  }
  for (const probe of surface.probes) {
    if (typeof probe.id !== "string" || probeIDs.has(probe.id)) throw new Error(`duplicate stealth probe ${probe.id}`);
    if (!["native-equal", "owned-internal-names-absent"].includes(probe.expected_relation)) throw new Error(`invalid stealth relation ${probe.id}`);
    probeIDs.add(probe.id);
    probeCount += 1;
  }
}
if (source.limits?.surface_count !== source.surfaces.length
  || source.limits?.probe_count !== probeCount
  || probeCount < 48
  || probeCount > 64) {
  throw new Error("stealth profile limits do not match inventory");
}
const moduleSource = `// Generated by scripts/generate-stealth-profile.mjs. DO NOT EDIT.\nconst profile = ${JSON.stringify(source)};\nfor (const browser of profile.browser_scope) Object.freeze(browser);\nfor (const surface of profile.surfaces) { for (const probe of surface.probes) Object.freeze(probe); Object.freeze(surface.probes); Object.freeze(surface); }\nObject.freeze(profile.browser_scope); Object.freeze(profile.limits); Object.freeze(profile.comparison); Object.freeze(profile.surfaces);\nexport const STEALTH_PROFILE = Object.freeze(profile);\n`;
if (mode === "--check") {
  if (await readFile(outputPath, "utf8") !== moduleSource) throw new Error("generated stealth profile is stale");
} else {
  await writeFile(outputPath, moduleSource);
}
