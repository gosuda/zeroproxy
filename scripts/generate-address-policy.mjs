import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const rulesPath = new URL("./protocol/address-policy.rules.json", root);
const outputs = {
  policy: new URL("./protocol/address-policy.json", root),
  go: new URL("./internal/policy/address_policy_generated.go", root),
  js: new URL("./web/generated/address-policy.mjs", root),
};

function validate(rules) {
  if (!rules || rules.schema_version !== 1
    || rules.policy_id !== "zeroproxy-address-policy-v1"
    || rules.hostname_canonicalization !== "UTS46_IDNA2008_LOOKUP"
    || rules.socks_address_type !== "DOMAIN"
    || rules.reject_ip_literals !== true
    || rules.reject_single_label !== true
    || !Array.isArray(rules.blocked_suffixes)
    || rules.blocked_suffixes.length === 0) throw new Error("invalid address policy rules");
  const sorted = [...new Set(rules.blocked_suffixes)].sort();
  if (JSON.stringify(sorted) !== JSON.stringify(rules.blocked_suffixes)
    || sorted.some(value => !/^[a-z0-9.-]{1,253}$/u.test(value))) {
    throw new Error("address policy suffixes must be unique, canonical, and sorted");
  }
  return rules;
}

function goSource(rules) {
  const suffixes = rules.blocked_suffixes.map(value => `\t${JSON.stringify(value)},`).join("\n");
  return `// Code generated by scripts/generate-address-policy.mjs; DO NOT EDIT.\n\npackage policy\n\nconst AddressPolicyID = ${JSON.stringify(rules.policy_id)}\n\nvar blockedAddressSuffixes = [...]string{\n${suffixes}\n}\n`;
}

function jsSource(rules) {
  return `// Code generated by scripts/generate-address-policy.mjs; DO NOT EDIT.\nexport const ADDRESS_POLICY_ID = ${JSON.stringify(rules.policy_id)};\nexport const BLOCKED_ADDRESS_SUFFIXES = Object.freeze(${JSON.stringify(rules.blocked_suffixes)});\n`;
}

const rules = validate(JSON.parse(await readFile(rulesPath, "utf8")));
const generated = {
  policy: `${JSON.stringify(rules, null, 2)}\n`,
  go: goSource(rules),
  js: jsSource(rules),
};
const check = process.argv.includes("--check");
for (const [name, url] of Object.entries(outputs)) {
  if (check) {
    const current = await readFile(url, "utf8").catch(() => "");
    if (current !== generated[name]) throw new Error(`${url.pathname} is stale`);
  } else {
    await writeFile(url, generated[name]);
  }
}
