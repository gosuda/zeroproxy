import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const sourcePath = path.join(root, "protocol/native-failure-shapes.json");
const outputPath = path.join(root, "web/generated/native-failure-shapes.mjs");
const mode = process.argv[2] ?? "";
if (!["", "--check"].includes(mode)) throw new Error("usage: generate-native-failure-shapes.mjs [--check]");

const requiredSurfaces = Object.freeze([
  "navigation",
  "classic-script",
  "module-script",
  "eval-function",
  "dynamic-policy-sync",
  "dynamic-policy-async",
  "css",
  "import-map",
  "fetch-cors-transport",
  "websocket",
  "runtime-install",
]);
const source = JSON.parse(await readFile(sourcePath, "utf8"));
if (source.schema_version !== 1 || source.table_version !== 1 || !Array.isArray(source.rows)) throw new Error("invalid native failure table header");
if (source.rows.length !== requiredSurfaces.length) throw new Error("native failure table must cover every required surface exactly once");
const ids = new Set();
const tests = new Set();
for (let index = 0; index < source.rows.length; index += 1) {
  const row = source.rows[index];
  if (row.surface !== requiredSurfaces[index]) throw new Error(`native failure surface order mismatch at ${requiredSurfaces[index]}`);
  if (typeof row.id !== "string" || ids.has(row.id) || typeof row.test_id !== "string") throw new Error(`invalid native failure row ${row.id ?? index}`);
  if (row.original_bytes_executed !== false || !Array.isArray(row.terminal_events) || row.terminal_events.length === 0) throw new Error(`unsafe native failure row ${row.id}`);
  ids.add(row.id);
  tests.add(row.test_id);
}
if (tests.size < 5) throw new Error("native failure table must cite independent product oracles");

const moduleSource = `// Generated by scripts/generate-native-failure-shapes.mjs. DO NOT EDIT.\nexport const NATIVE_FAILURE_TABLE_VERSION = ${source.table_version};\nexport const NATIVE_FAILURE_SHAPES = Object.freeze(Object.fromEntries(${JSON.stringify(source.rows)}.map(row => [row.surface, Object.freeze({...row, terminal_events:Object.freeze(row.terminal_events)})])));\n`;
if (mode === "--check") {
  if (await readFile(outputPath, "utf8") !== moduleSource) throw new Error("generated native failure table is stale");
} else {
  await writeFile(outputPath, moduleSource);
}
